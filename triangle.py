def area(a,h):
    '''Функция подсчета площади треугольника принимает параметры a и h - сторона и высота
    треугольника и возвращает его площадь: (a*h)/2'''
    return (a*h)/2

def perimetr(a,b,c):
    '''Функция подсчета периметра треугольника принимает параметры a,b,c - стороны
    треугольника и возвращает его периметр: a + b + c'''
    return a + b + c
