def triangle_area(a,h):
    '''Функция подсчета площади треугольника принимает параметры a и h - сторона и высота
    треугольника прилегающая к стороне a, и возвращает его площадь 
    (полупроизведение высоты на сторону, к которой она прилегает): (a*h)/2'''
    return (a*h)/2

def triangle_perimeter(a,b,c):
    '''Функция подсчета периметра треугольника принимает параметры a,b,c - стороны
    треугольника и возвращает его периметр (сумму всех сторон): a + b + c'''
    return a + b + c
