
def square_area(a):
    '''Функция подсчета площади квадрата принимает параметр a - сторона
    фигуры и возвращает ее площадь (квадрат стороны): a**2 или a*a'''
    return a * a


def square_perimeter(a):
    '''Функция подсчета периметра квадрата принимает параметр a - сторона
    фигуры и возвращает ее периметр (сторона * 4): 4*а'''
    return 4 * a
