
def area(a):
    '''Функция подсчета площади квадрата принимает параметр a - сторона
    фигуры и возвращает ее площадь (квадрат): a**2 или a*a'''
    return a * a


def perimeter(a):
    '''Функция подсчета периметра квадрата принимает параметр a - сторона
    фигуры и возвращает ее периметр: 4*а'''
    return 4 * a
